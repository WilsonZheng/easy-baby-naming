export interface SourceEntry {
  line: string
  ref: string
  /**
   * 讲凋零、离别、死亡、荒芜的句子。文学价值不影响它们不适合当名字出处 ——
   * 「惟草木之零落兮，恐美人之迟暮」很美，但没人会用它给孩子取名。
   * 这类句子留在库里是为了不误判，但绝不引用。
   */
  inauspicious: boolean
  /** 该句包含的全部汉字（去重），用于快速匹配 */
  chars: Set<string>
  /** 去掉标点后的纯汉字串，用来判断两个字的先后顺序 */
  plain: string
  /** 按标点切开的分句（同样只保留汉字），预计算以免生成时反复拆分 */
  clauses: string[]
}

export const SOURCES: SourceEntry[] = RAW.split('\n').map((row) => {
  const [line, marked] = row.split('|')
  const inauspicious = marked.startsWith('!')
  const ref = inauspicious ? marked.slice(1) : marked
  const plain = line.replace(/[^一-龥]/g, '')
  const clauses = line.split(/[，。；、？！]/).map((c) => c.replace(/[^一-龥]/g, '')).filter(Boolean)
  return { line, ref, inauspicious, chars: new Set(plain.split('')), plain, clauses }
})

/**
 * 两个字必须同时出现在同一句里、顺序与原句一致，且这句话本身适合当出处。
 *
 * 顺序这一条很关键：「地势坤，君子以厚德载物」支持「坤德」，不支持「德坤」。
 * 少了它就会造出语序颠倒、读着别扭的名字。
 */
export function findSource(a: string, b: string): SourceEntry | undefined {
  return SOURCES.find((s) => {
    if (s.inauspicious || !s.chars.has(a) || !s.chars.has(b)) return false
    return s.plain.indexOf(a) < s.plain.lastIndexOf(b)
  })
}

/**
 * 更严的一档：两个字要落在同一个分句里。
 *
 * 「等闲识得东风面，万紫千红总是春」里确实先有「风」后有「春」，
 * 但它们分属两个分句、两个意象，拼成「风春」并不成词。
 * 判断「这两个字本来就是一路的」用这一档；仅仅展示引用用宽的那一档。
 */
export function findSourceSameClause(a: string, b: string): SourceEntry | undefined {
  return SOURCES.find((s) => {
    if (s.inauspicious || !s.chars.has(a) || !s.chars.has(b)) return false
    return s.clauses.some((c) => {
      const i = c.indexOf(a)
      return i >= 0 && i < c.lastIndexOf(b)
    })
  })
}

export const AUSPICIOUS_SOURCE_COUNT = SOURCES.filter((s) => !s.inauspicious).length
