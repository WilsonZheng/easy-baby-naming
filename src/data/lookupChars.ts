export interface LookupChar {
  char: string
  pinyin: string
  tone: 1 | 2 | 3 | 4
  meaning: string
}

/**
 * 查这个字。主字库优先 —— 那里的信息更全（五行、笔画都逐字核过）。
 * 主字库没有才回落到这张表。
 */
export const LOOKUP_CHARS: Map<string, LookupChar> = new Map(
  RAW.split('\n')
    .map((row) => row.split('|'))
    .filter((p) => p.length === 4 && /^[一-龥]$/.test(p[0]))
    .map(([char, pinyin, tone, meaning]) => [
      char,
      { char, pinyin, tone: Number(tone) as LookupChar['tone'], meaning },
    ]),
)
